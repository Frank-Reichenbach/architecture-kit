// Renders every view of every project in the workspace and writes renders/README.md as a review index.
// Refuses to render a model that fails the check.
//
// Renderers: deployment views (infrastructure, networks) → D2 with ELK layout → <viewId>.png (lib/d2.mjs);
//            all other views (landscape, containers, sequences) → LikeC4 → <viewId>.jpg.
// Output: renders/ for a single project, renders/<project>/ when the workspace has several.

import { LikeC4 } from 'likec4'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { check } from './check.mjs'
import { renderDeploymentView } from './d2.mjs'
import { findProjects } from './workspace.mjs'

const require = createRequire(import.meta.url)

export function likec4Bin() {
  const pkgFile = require.resolve('likec4/package.json')
  const { bin } = JSON.parse(readFileSync(pkgFile, 'utf8'))
  return path.join(path.dirname(pkgFile), typeof bin === 'string' ? bin : bin.likec4)
}

export function hasD2() {
  try {
    execFileSync('d2', ['--version'], { stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

// Same semantics as LikeC4's --filter: glob patterns on view ids, combined with OR
const globToRegex = glob => new RegExp(`^${glob.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*').replace(/\?/g, '.')}$`)

/**
 * @param workspace architecture workspace directory
 * @param options   { project, filters: [glob], log }
 * @returns true on success
 */
export async function render(workspace, { project: onlyProject, filters = [], log = console.log } = {}) {
  if (!(await check(workspace, { log }))) {
    log('\nNot rendering: fix the errors above first.')
    return false
  }

  const all = findProjects(workspace)
  const projects = all.filter(p => !onlyProject || p.name === onlyProject)
  if (projects.length === 0) {
    log(`Unknown project '${onlyProject}'. Known: ${all.map(p => p.name).join(', ')}`)
    return false
  }
  const outdir = path.join(workspace, 'renders')
  const cacheDir = path.join(workspace, '.cache')
  const projectOut = p => (all.length === 1 ? outdir : path.join(outdir, p.name))
  const partial = filters.length > 0 || onlyProject

  // A full render replaces everything, so images of deleted or renamed views disappear.
  if (!partial) rmSync(outdir, { recursive: true, force: true })

  for (const p of projects) {
    mkdirSync(projectOut(p), { recursive: true })
    // JPG, not PNG: LikeC4's PNGs have a transparent background that is unreadable in dark viewers.
    // --sequence renders dynamic views as sequence diagrams.
    // Export from the project's own folder: with several projects in one workspace, LikeC4 1.59
    // only exports the first one correctly (wrong export URLs for the others).
    execFileSync(process.execPath, [
      likec4Bin(), 'export', 'jpg', p.dir,
      '--outdir', projectOut(p),
      '--flat',
      '--sequence',
      ...filters.flatMap(f => ['--filter', f]),
    ], { stdio: ['ignore', 'ignore', 'inherit'] })
  }

  const likec4 = await LikeC4.fromWorkspace(workspace, { logger: false })
  try {
    // Deployment views through D2
    if (!hasD2()) {
      log('warn: d2 not found (brew install d2); deployment views keep the LikeC4 rendering.')
    } else {
      const matches = id => filters.length === 0 || filters.some(f => globToRegex(f).test(id))
      for (const p of projects) {
        const model = await likec4.computedModel(p.name)
        for (const view of model.views()) {
          if (!view.isDeploymentView() || !matches(view.id)) continue
          const { layout, ratio } = await renderDeploymentView(view, path.join(projectOut(p), `${view.id}.png`), {
            workDir: path.join(cacheDir, 'd2', p.name),
            iconDir: path.join(cacheDir, 'icons'),
          })
          rmSync(path.join(projectOut(p), `${view.id}.jpg`), { force: true })
          log(`d2: ${path.relative(workspace, projectOut(p)) || '.'}/${view.id}.png (${layout}, height:width ${ratio})`)
        }
      }
    }

    // Review index, always covering all projects
    const groups = [
      ['Landscape and cross-cutting views', v => v.isElementView() && !v.isScopedElementView()],
      ['Systems (containers)', v => v.isScopedElementView()],
      ['Scenarios (sequence)', v => v.isDynamicView()],
      ['Infrastructure and network', v => v.isDeploymentView()],
    ]
    const sortKey = v => (v.id === 'index' ? '' : v.titleOrId)
    const lines = ['# Architecture diagrams', '', '> Generated by `architecture-kit render`; do not edit.', '']
    for (const p of all) {
      const model = await likec4.computedModel(p.name)
      const rel = path.relative(outdir, projectOut(p))
      lines.push(`## ${p.title}`, '', `Project \`${p.name}\`, sources in \`${path.relative(workspace, p.dir) || '.'}/\``, '')
      for (const [heading, match] of groups) {
        const views = [...model.views()].filter(match).sort((a, b) => sortKey(a).localeCompare(sortKey(b)))
        if (views.length === 0) continue
        lines.push(`### ${heading}`, '')
        for (const v of views) {
          lines.push(`#### ${v.titleOrId}`, '')
          if (v.description && !v.description.isEmpty) lines.push(v.description.text, '')
          const image = ['png', 'jpg'].map(ext => path.join(rel, `${v.id}.${ext}`)).find(f => existsSync(path.join(outdir, f)))
          lines.push(`View \`${v.id}\``, '', image ? `![${v.titleOrId}](./${image})` : '_not rendered_', '')
        }
      }
    }
    mkdirSync(outdir, { recursive: true })
    writeFileSync(path.join(outdir, 'README.md'), lines.join('\n'))
    log(`Wrote ${path.relative(process.cwd(), path.join(outdir, 'README.md'))}`)
    return true
  } finally {
    await likec4.dispose()
  }
}
